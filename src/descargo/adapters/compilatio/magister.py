"""The Compilatio Magister layout used until 2025 ("INFORME DE ANÁLISIS").

The first page holds the results (suspicious text, similarity, quoted similarity,
unrecognised languages and text "potentially generated by AI"), the document's details and
the source tables: main sources, incidental sources and sources the document cites without
any similarity. A result may end in "(ignorado)". The pages after it reproduce the
document. Passages that Compilatio attributes to AI are drawn in one colour; passages that
match a source are highlighted behind the text, which the PDF's text does not expose.
"""

import re
from dataclasses import dataclass, field
from typing import Any

from pypdf import PdfReader

from descargo.adapters.base import AdapterError
from descargo.adapters.compilatio.common import (
    AI_COLOUR,
    NUMBER,
    Download,
    Words,
    after,
    build_report,
    count,
    day,
    joined_runs,
    overlap_warnings,
    same,
    submission,
    value,
)
from descargo.core.report_schema import (
    AiSegment,
    AiWriting,
    Report,
    Similarity,
    Source,
    SourceKind,
)
from descargo.i18n import t

_URL = re.compile(r"https?://")
_RESULTS = ("suspicious", "similarity", "quoted", "cited", "unrecognised_languages", "ai")


def recognises(lines: list[str], words: Words) -> bool:
    head = lines[:40]
    return words["heading"] in head and any(words["similarity"] in line for line in head)


def _results(head: list[str], words: Words) -> tuple[dict[str, tuple[float, bool]], list[str]]:
    """The percentages on the first page, keyed like ``labels.yaml``, and the keys of those
    marked "(ignorado)". A label may wrap over several lines."""
    end = next((i for i, line in enumerate(head) if line.startswith(words["document_name"])), 40)
    text = " ".join(head[:end])
    results: dict[str, tuple[float, bool]] = {}
    ignored = []
    for key in _RESULTS:
        label = re.escape(words[key])
        match = re.search(rf"{NUMBER}\s*{label}(\s*{re.escape(words['ignored'])})?", text)
        if match:
            results[key] = value(match)
            if match.group(3):
                ignored.append(key)
    return results, ignored


@dataclass
class _Parsed:
    sources: list[Source] = field(default_factory=list)
    groups: dict[str, str] = field(default_factory=dict)
    mentioned: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def _source_row(text: str, group: str, words: Words, parsed: _Parsed) -> None:
    """One row of a source table, without its "identical words" ending."""
    row = re.match(rf"^(\d+)\s+(.*?)\s*(?:\d+\s+{words['similar_sources']}\s*)?{NUMBER}\s*$", text)
    if row is None:
        parsed.warnings.append(t("adapters.warn_unknown_row", text=text))
        return
    rank, body = int(row.group(1)), row.group(2)
    percent, bound = value(row, 3)
    url_at = _URL.search(body)
    label = (body[: url_at.start()] if url_at else body).strip() or body.strip()
    url = body[url_at.start() :].strip() if url_at else None
    if url is not None and (url.endswith(("...", "…")) or " " in url):
        url = None  # shortened on the report
    kind = SourceKind.UNKNOWN
    if label.startswith(words["other_user_document"]):
        kind = SourceKind.STUDENT_PAPER
    elif url_at:
        kind = SourceKind.INTERNET
    source_id = f"{group[0]}{rank}"
    if source_id in parsed.groups:
        parsed.warnings.append(t("adapters.warn_duplicate_source", source=rank))
        return
    parsed.groups[source_id] = group
    parsed.sources.append(
        Source(
            id=source_id,
            rank=rank,
            label=label,
            kind=kind,
            url=url,
            percent=percent,
            percent_is_upper_bound=bound,
        )
    )


def _table(lines: list[str], group: str, words: Words, parsed: _Parsed) -> None:
    """Rows end with "Palabras idénticas: <1% (38 palabras)"; a row may wrap over lines."""
    text = " ".join(line for line in lines if not line.startswith(words["table_header"]))
    ending = re.compile(
        rf"{re.escape(words['identical_words'])}\s*{NUMBER}\s*\((\d+)\s*{words['words']}\)"
    )
    start = 0
    for match in ending.finditer(text):
        before = len(parsed.sources)
        _source_row(text[start : match.start()].strip(), group, words, parsed)
        if len(parsed.sources) > before:
            parsed.sources[-1] = parsed.sources[-1].model_copy(
                update={"matched_words": int(match.group(3))}
            )
        start = match.end()
    if text[start:].strip():
        parsed.warnings.append(t("adapters.warn_text_after_table"))


def _tables(lines: list[str], words: Words) -> _Parsed:
    parsed = _Parsed()
    headings = {
        "main": words["main_sources"],
        "incidental": words["incidental_sources"],
        "mentioned": words["mentioned_sources"],
        "end": words["points_of_interest"],
    }
    starts = {
        key: next((i for i, line in enumerate(lines) if line.startswith(label)), None)
        for key, label in headings.items()
    }
    found = sorted((index, key) for key, index in starts.items() if index is not None)
    for position, (index, key) in enumerate(found):
        end = found[position + 1][0] if position + 1 < len(found) else len(lines)
        if key in {"main", "incidental"}:
            _table(lines[index + 1 : end], key, words, parsed)
        elif key == "mentioned":
            for line in lines[index + 1 : end]:
                cited = re.match(r"^\d+\s+(https?://\S+)$", line)
                if cited is None:
                    break
                parsed.mentioned.append(cited.group(1))
    if starts["main"] is None and starts["incidental"] is None:
        parsed.warnings.append(t("adapters.warn_no_source_table"))
    return parsed


class _ColourRuns:
    """Collects, for one page, the runs of text drawn in one colour (a pypdf visitor)."""

    def __init__(self, colour: tuple[float, ...]) -> None:
        self.colour = colour
        self.fill: tuple[float, ...] | None = None
        self.runs: list[list[tuple[float, str]]] = [[]]

    def before(self, operator: bytes, operands: list[object], _cm: object, _tm: object) -> None:
        if operator not in {b"rg", b"sc", b"scn", b"g"}:
            return
        values = [float(o) for o in operands if isinstance(o, int | float)]
        if operator == b"g" and len(values) == 1:
            values *= 3
        self.fill = tuple(values) if len(values) == 3 else None

    def text(
        self, content: str, _cm: object, tm: list[float], _font: object, _size: object
    ) -> None:
        run = self.runs[-1]
        if not content.strip():
            if run:
                run.append((tm[5], " "))
        elif same(self.fill, self.colour):
            run.append((tm[5], content))
        elif run:
            self.runs.append([])


def _ai_segments(reader: PdfReader) -> list[AiSegment]:
    """Runs of text drawn in :data:`AI_COLOUR`, page by page, from the second page on.
    A run ends at any visible text in another colour, and at the end of a page."""
    segments: list[AiSegment] = []
    for number, page in enumerate(reader.pages[1:], start=2):
        runs = _ColourRuns(AI_COLOUR)
        page.extract_text(visitor_operand_before=runs.before, visitor_text=runs.text)
        segments += [AiSegment(text=text, page=number) for text in joined_runs(runs.runs)]
    return segments


def parse(
    reader: PdfReader,
    lines: list[str],
    words: Words,
    language: str,
    download: Download,
) -> Report:
    end = next((i for i, line in enumerate(lines) if line == words["points_of_interest"]), None)
    head = lines[:end]
    results, ignored = _results(head, words)
    warnings: list[str] = []
    if "similarity" not in results:
        raise AdapterError("the overall similarity percentage could not be read")
    overall, overall_bound = results["similarity"]
    if overall_bound:
        warnings.append(t("adapters.warn_overall_bound", percent=f"{overall:g}"))

    parsed = _tables(head, words)
    warnings += parsed.warnings
    if "suspicious" in results and not results["suspicious"][1]:
        warnings += overlap_warnings(parsed.sources, results["suspicious"][0], "suspicious")
    elif not overall_bound:
        warnings += overlap_warnings(parsed.sources, overall, "overall")

    ai_writing = None
    if "ai" in results:
        segments = _ai_segments(reader)
        ai_writing = AiWriting(overall_percent=results["ai"][0], segments=segments)
        if results["ai"][0] > 0 and not segments:
            warnings.append(t("adapters.warn_compilatio_ai_no_colour"))
        elif segments:
            warnings.append(t("adapters.warn_compilatio_ai_colour"))
        if "ai" in ignored:
            warnings.append(t("adapters.warn_ai_ignored"))
    else:
        warnings.append(t("adapters.warn_no_ai_percent"))

    product = head[head.index(words["heading"]) + 1] if words["heading"] in head[:-1] else None
    extensions: dict[str, Any] = {
        "layout": "magister",
        "language": language,
        "source_groups": parsed.groups,
        "mentioned_sources": parsed.mentioned,
        "deposited_on": day(after(head, words["deposited_on"])),
        "analysed_on": day(after(head, words["analysed_on"])),
        "marked_ignored": ignored,
    }
    for key in ("suspicious", "quoted", "cited", "unrecognised_languages"):
        if key in results:
            extensions[f"{key}_percent"] = results[key][0]
            extensions[f"{key}_percent_is_upper_bound"] = results[key][1]
    return build_report(
        download,
        f"Compilatio {product.capitalize()}" if product else "Compilatio",
        submission(
            after(head, words["document_name"], stop=words["document_id"]),
            count(after(head, words["word_count"])),
            count(after(head, words["character_count"])),
        ),
        Similarity(overall_percent=overall, sources=parsed.sources),
        ai_writing,
        warnings,
        extensions,
    )
