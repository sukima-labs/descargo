"""Read a Compilatio analysis report downloaded as PDF into the common report schema.

The first page holds the results (suspicious text, similarity, quoted similarity,
unrecognised languages and text "potentially generated by AI"), the document's details and
the source tables: main sources, incidental sources and sources the document cites without
any similarity. The pages after it reproduce the document. Passages that Compilatio
attributes to AI are drawn in one colour; passages that match a source are highlighted
behind the text, which the PDF's text does not expose.

So the report carries sources but no matched passages, and the auditor uses its
approximate method (ADR 005), as with Turnitin. The AI passages are read from their colour.
Following ADR 004, the adapter never keeps the depositor's name or the document ID, never
invents a value it could not read, and adds a warning instead.
"""

import re
import unicodedata
from dataclasses import dataclass, field
from datetime import date, datetime
from functools import cache
from importlib.resources import files
from typing import Any, Final

import yaml
from pypdf import PdfReader

from draftwitness import __version__
from draftwitness.adapters.base import AdapterError
from draftwitness.adapters.pdftext import open_pdf, pdf_lines
from draftwitness.core.report_schema import (
    AiSegment,
    AiWriting,
    Provenance,
    Report,
    ReportFile,
    ReportKind,
    Similarity,
    Source,
    SourceKind,
    Submission,
    Tool,
)

ADAPTER_NAME: Final = "compilatio-pdf"
ADAPTER_VERSION: Final = "0.1"
AI_COLOUR: Final = (0.0, 0.75, 1.0)
"""Fill colour of the text Compilatio attributes to AI, as RGB from 0 to 1."""
_TOLERANCE: Final = 0.02
_NUMBER = r"(<\s*)?(\d+(?:[.,]\d+)?)\s*%"
_DATE = re.compile(r"(\d{2})/(\d{2})/(\d{4})")
_URL = re.compile(r"https?://")


@cache
def labels() -> dict[str, dict[str, str]]:
    text = files("draftwitness.adapters.compilatio").joinpath("labels.yaml").read_text("utf-8")
    data: dict[str, dict[str, str]] = yaml.safe_load(text)
    return data


def detect_language(lines: list[str]) -> str | None:
    """The language of the Compilatio report whose lines these are, or ``None``."""
    head = lines[:40]
    for language, words in labels().items():
        if words["heading"] in head and any(line.endswith(words["similarity"]) for line in head):
            return language
    return None


def _value(match: re.Match[str]) -> tuple[float, bool]:
    return float(match.group(2).replace(",", ".")), bool(match.group(1))


def _results(head: list[str], words: dict[str, str]) -> dict[str, tuple[float, bool]]:
    """The percentages on the first page, keyed like ``labels.yaml``."""
    keys = {words[k]: k for k in ("similarity", "quoted", "cited", "unrecognised_languages", "ai")}
    results: dict[str, tuple[float, bool]] = {}
    for index, line in enumerate(head):
        match = re.match(rf"^{_NUMBER}\s*(.+)$", line)
        if match and match.group(3) in keys:
            results.setdefault(keys[match.group(3)], _value(match))
        elif line == words["suspicious"] and index > 0:
            value = re.match(rf"^{_NUMBER}$", head[index - 1])
            if value:
                results.setdefault("suspicious", _value(value))
    return results


def _after(head: list[str], label: str) -> str | None:
    for line in head:
        if line.startswith(label):
            return line[len(label) :].strip() or None
    return None


def _count(text: str | None) -> int | None:
    digits = (text or "").replace(".", "").replace(",", "").replace(" ", "")
    return int(digits) if digits.isdigit() else None


def _day(text: str | None) -> str | None:
    match = _DATE.search(text or "")
    if match is None:
        return None
    try:
        return date(int(match.group(3)), int(match.group(2)), int(match.group(1))).isoformat()
    except ValueError:
        return None


@dataclass
class _Parsed:
    sources: list[Source] = field(default_factory=list)
    groups: dict[str, str] = field(default_factory=dict)
    mentioned: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def _source_row(text: str, group: str, words: dict[str, str], parsed: _Parsed) -> None:
    """One row of a source table, without its "identical words" ending."""
    row = re.match(rf"^(\d+)\s+(.*?)\s*(?:\d+\s+{words['similar_sources']}\s*)?{_NUMBER}\s*$", text)
    if row is None:
        parsed.warnings.append(f"A row of the source table was not understood: “{text}”.")
        return
    rank, body = int(row.group(1)), row.group(2)
    percent = float(row.group(4).replace(",", "."))
    url_at = _URL.search(body)
    label = (body[: url_at.start()] if url_at else body).strip() or body.strip()
    url = body[url_at.start() :].strip() if url_at else None
    if url is not None and (url.endswith("...") or " " in url):
        url = None  # shortened on the report
    kind = SourceKind.UNKNOWN
    if label.startswith(words["other_user_document"]):
        kind = SourceKind.STUDENT_PAPER
    elif url_at:
        kind = SourceKind.INTERNET
    source_id = f"{group[0]}{rank}"
    if source_id in parsed.groups:
        parsed.warnings.append(f"Source {rank} appears twice in one table; the second was ignored.")
        return
    parsed.groups[source_id] = group
    parsed.sources.append(
        Source(
            id=source_id,
            rank=rank,
            label=label,
            kind=kind,
            url=url,
            percent=percent,
            percent_is_upper_bound=bool(row.group(3)),
        )
    )


def _with_words(source: Source, match: re.Match[str]) -> Source:
    return source.model_copy(update={"matched_words": int(match.group(1))})


def _table(lines: list[str], group: str, words: dict[str, str], parsed: _Parsed) -> None:
    """Rows end with "Palabras idénticas: <1% (38 palabras)"; a row may wrap over lines."""
    text = " ".join(line for line in lines if not line.startswith(words["table_header"]))
    ending = re.compile(
        rf"{re.escape(words['identical_words'])}\s*{_NUMBER}\s*\((\d+)\s*{words['words']}\)"
    )
    start = 0
    for match in ending.finditer(text):
        before = len(parsed.sources)
        _source_row(text[start : match.start()].strip(), group, words, parsed)
        if len(parsed.sources) > before:
            words_match = re.match(r"(\d+)", match.group(3))
            if words_match:
                parsed.sources[-1] = _with_words(parsed.sources[-1], words_match)
        start = match.end()
    if text[start:].strip():
        parsed.warnings.append(
            "Some text after the source table was not recognised as a source and was ignored."
        )


def _tables(lines: list[str], words: dict[str, str]) -> _Parsed:
    parsed = _Parsed()
    headings = {
        "main": words["main_sources"],
        "incidental": words["incidental_sources"],
        "mentioned": words["mentioned_sources"],
        "end": words["points_of_interest"],
    }
    starts = {
        key: next((i for i, line in enumerate(lines) if line.startswith(label)), None)
        for key, label in headings.items()
    }
    found = sorted((index, key) for key, index in starts.items() if index is not None)
    for position, (index, key) in enumerate(found):
        end = found[position + 1][0] if position + 1 < len(found) else len(lines)
        if key in {"main", "incidental"}:
            _table(lines[index + 1 : end], key, words, parsed)
        elif key == "mentioned":
            for line in lines[index + 1 : end]:
                cited = re.match(r"^\d+\s+(https?://\S+)$", line)
                if cited is None:
                    break
                parsed.mentioned.append(cited.group(1))
    if starts["main"] is None and starts["incidental"] is None:
        parsed.warnings.append("No source table was found on the report.")
    return parsed


def _same(colour: tuple[float, ...] | None, wanted: tuple[float, ...]) -> bool:
    return (
        colour is not None
        and len(colour) == len(wanted)
        and all(abs(a - b) <= _TOLERANCE for a, b in zip(colour, wanted, strict=True))
    )


class _ColourRuns:
    """Collects, for one page, the runs of text drawn in one colour (a pypdf visitor)."""

    def __init__(self, colour: tuple[float, ...]) -> None:
        self.colour = colour
        self.fill: tuple[float, ...] | None = None
        self.runs: list[list[tuple[float, str]]] = [[]]

    def before(self, operator: bytes, operands: list[object], _cm: object, _tm: object) -> None:
        if operator not in {b"rg", b"sc", b"scn", b"g"}:
            return
        values = [float(o) for o in operands if isinstance(o, int | float)]
        if operator == b"g" and len(values) == 1:
            values *= 3
        self.fill = tuple(values) if len(values) == 3 else None

    def text(
        self, content: str, _cm: object, tm: list[float], _font: object, _size: object
    ) -> None:
        run = self.runs[-1]
        if not content.strip():
            if run:
                run.append((tm[5], " "))
        elif _same(self.fill, self.colour):
            run.append((tm[5], content))
        elif run:
            self.runs.append([])

    def texts(self) -> list[str]:
        """Each run's text. Pieces on different lines are joined with a space."""
        texts = []
        for run in self.runs:
            joined = ""
            last_y: float | None = None
            for y, piece in run:
                wrapped = last_y is not None and y != last_y
                if wrapped and joined and not joined[-1].isspace() and not piece[:1].isspace():
                    joined += " "
                joined += piece
                last_y = y
            text = " ".join(unicodedata.normalize("NFKC", joined).split())
            if text:
                texts.append(text)
        return texts


def _ai_segments(reader: PdfReader) -> list[AiSegment]:
    """Runs of text drawn in :data:`AI_COLOUR`, page by page, from the second page on.
    A run ends at any visible text in another colour, and at the end of a page."""
    segments: list[AiSegment] = []
    for number, page in enumerate(reader.pages[1:], start=2):
        runs = _ColourRuns(AI_COLOUR)
        page.extract_text(visitor_operand_before=runs.before, visitor_text=runs.text)
        segments += [AiSegment(text=text, page=number) for text in runs.texts()]
    return segments


def parse_pdf(
    data: bytes,
    filename: str,
    sha256: str,
    *,
    parsed_at: datetime,
    lines: list[str] | None = None,
) -> Report:
    """Turn a downloaded Compilatio PDF report into a :class:`Report`. ``lines`` are the
    report's :func:`~draftwitness.adapters.pdftext.pdf_lines`, if already extracted."""
    reader = open_pdf(data)
    lines = pdf_lines(data) if lines is None else lines
    language = detect_language(lines)
    if language is None:
        raise AdapterError("not a Compilatio analysis report DraftWitness can read")
    words = labels()[language]
    end = next((i for i, line in enumerate(lines) if line == words["points_of_interest"]), None)
    head = lines[:end]
    results = _results(head, words)
    warnings: list[str] = []
    if "similarity" not in results:
        raise AdapterError("the overall similarity percentage could not be read")
    overall, overall_bound = results["similarity"]
    if overall_bound:
        warnings.append(
            f"The report shows the overall similarity as “<{overall:g}%”; {overall:g}% is used."
        )

    parsed = _tables(head, words)
    warnings += parsed.warnings
    for source in parsed.sources:
        if source.percent is not None and source.percent > overall and not overall_bound:
            warnings.append(
                f"Source {source.label} is shown with {source.percent:g}%, more than the overall "
                f"{overall:g}%: the report may have been misread or edited."
            )

    ai_writing = None
    if "ai" in results:
        segments = _ai_segments(reader)
        ai_writing = AiWriting(overall_percent=results["ai"][0], segments=segments)
        if results["ai"][0] > 0 and not segments:
            warnings.append(
                "The report gives an AI percentage, but no passage drawn in Compilatio's AI "
                "colour was found; the flagged passages could not be read."
            )
        elif segments:
            warnings.append(
                "The passages Compilatio attributes to AI were read from their colour in the "
                "PDF; check them against the report."
            )
    else:
        warnings.append("The AI percentage could not be read.")
    warnings.append(
        "Compilatio PDF reports show matched passages only as highlights, so the report has "
        "sources but no matched text; the audit uses its approximate method."
    )

    name = _after(head, words["document_name"])
    product = head[head.index(words["heading"]) + 1] if words["heading"] in head[:-1] else None
    extensions: dict[str, Any] = {
        "language": language,
        "source_groups": parsed.groups,
        "mentioned_sources": parsed.mentioned,
        "deposited_on": _day(_after(head, words["deposited_on"])),
        "analysed_on": _day(_after(head, words["analysed_on"])),
    }
    for key in ("suspicious", "quoted", "cited", "unrecognised_languages"):
        if key in results:
            extensions[f"{key}_percent"] = results[key][0]
            extensions[f"{key}_percent_is_upper_bound"] = results[key][1]
    return Report(
        tool=Tool(
            name="compilatio",
            product=f"Compilatio {product.capitalize()}" if product else "Compilatio",
            report_kind=ReportKind.COMBINED,
        ),
        provenance=Provenance(
            adapter=ADAPTER_NAME,
            adapter_version=ADAPTER_VERSION,
            draftwitness_version=__version__,
            parsed_at=parsed_at,
            report_file=ReportFile(
                filename=filename, media_type="application/pdf", sha256=sha256, size_bytes=len(data)
            ),
        ),
        submission=Submission(
            title=name.rsplit(".", 1)[0] if name else None,
            word_count=_count(_after(head, words["word_count"])),
            character_count=_count(_after(head, words["character_count"])),
        ),
        similarity=Similarity(overall_percent=overall, sources=parsed.sources),
        ai_writing=ai_writing,
        warnings=warnings,
        extensions={"compilatio": extensions},
    )
